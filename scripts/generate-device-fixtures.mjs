import { build } from "vite";
import { readFile, writeFile } from "node:fs/promises";

// Compile the existing fixture definitions; no second handwritten fixture set.
const result = await build({
  configFile: false,
  logLevel: "silent",
  build: {
    write: false,
    minify: false,
    lib: { entry: "packages/test-fixtures/src/index.ts", formats: ["es"] },
  },
});
const code = result[0].output.find((item) => item.type === "chunk").code;
const { fixtureScenarios } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const q = (value) => JSON.stringify(value ?? "");
const enumName = (value) =>
  value
    .toLowerCase()
    .split("_")
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
let out = `// Generated by scripts/generate-device-fixtures.mjs. Do not edit.\n#pragma once\n#include "apple/game_state/types.hpp"\n#include <vector>\n#include <string>\nnamespace apple::firmware {\nstruct LabFixtureFrame { std::uint32_t at_ms; game_state::CanonicalFrame frame; };\nstruct LabFixture { const char* id; std::uint32_t duration_ms; int expected_sequences; std::vector<LabFixtureFrame> frames; };\ninline const std::vector<LabFixture>& lab_fixtures() {\n  using namespace game_state;\n  static const std::vector<LabFixture> values = [] {\n    std::vector<LabFixture> list;\n`;
for (const scenario of fixtureScenarios) {
  const inputs = scenario.deviceFixture.frames;
  const duration = Math.max(scenario.frames.at(-1).atMs, inputs.at(-1).atMs);
  out += `    { LabFixture fixture{${q(scenario.id)}, ${duration}, ${scenario.deviceFixture.expectedMotionSequences}, {}};\n`;
  for (const { atMs, input: f } of inputs) {
    const visual = [...scenario.frames].reverse().find((v) => v.atMs <= atMs)?.snapshot ?? scenario.frames[0].snapshot;
    const team = (id) =>
      [visual.away, visual.home].find((t) => t.id === id) ?? {
        abbreviation: id === 121 ? "NYM" : "OPP",
        name: id === 121 ? "Mets" : "Opponent",
      };
    out += `      { CanonicalFrame f; f.game_pk=${f.gamePk}; f.game_number=${f.gameNumber}; f.cursor=${q(f.cursor)}; f.update_mode=UpdateMode::${enumName(f.updateMode)}; f.phase=Phase::${enumName(f.phase)}; f.half=Half::${enumName(f.half)}; f.inning=${f.inning}; f.display_outs=${f.outs}; f.evidence_outs=${f.outs}; f.label=${q(f.phase)}; f.last_event=${q(visual.lastEvent)};\n`;
    out += `        f.away={${f.awayTeamId},${q(team(f.awayTeamId).abbreviation)},${q(team(f.awayTeamId).name)},${f.awayRuns}}; f.home={${f.homeTeamId},${q(team(f.homeTeamId).abbreviation)},${q(team(f.homeTeamId).name)},${f.homeRuns}};\n`;
    if (visual.atBat) {
      const a = visual.atBat;
      out += `        { AtBatState a; a.balls=${a.balls}; a.strikes=${a.strikes}; a.bases={${a.bases.first},${a.bases.second},${a.bases.third}};`;
      for (const [key, field] of [
        ["batter", "batter"],
        ["batterLine", "batter_line"],
        ["pitcher", "pitcher"],
        ["pitchCount", "pitch_count"],
      ]) {
        if (a[key] !== undefined) out += ` a.${field}=${typeof a[key] === "number" ? a[key] : q(a[key])};`;
      }
      out += ` f.at_bat=std::move(a); }\n`;
    }
    for (const [key, field] of [
      ["scheduledStart", "scheduled_start"],
      ["venue", "venue"],
    ]) {
      if (visual[key] !== undefined) out += `        f.${field}=${q(visual[key])};\n`;
    }
    if (visual.linescore) {
      for (const inning of visual.linescore.innings)
        out += `        f.linescore.innings.push_back({${inning.inning},${inning.away ?? "std::nullopt"},${inning.home ?? "std::nullopt"}});\n`;
      for (const [key, field] of [
        ["awayHits", "away_hits"],
        ["homeHits", "home_hits"],
        ["awayErrors", "away_errors"],
        ["homeErrors", "home_errors"],
      ]) {
        if (visual.linescore[key] !== undefined) out += `        f.linescore.${field}=${visual.linescore[key]};\n`;
      }
    }
    for (const play of f.plays)
      out += `        f.changed_plays.push_back({${q(play.eventKey)},${play.atBatIndex},${play.battingTeamId},${q(play.batterName)},PlayKind::${enumName(play.kind)},${play.complete},ReviewState::${enumName(play.review)}});\n`;
    // Review display is copied from the scenario presentation, not inferred from plays.
    out += `        f.review=ReviewState::${enumName(visual.review)}; fixture.frames.push_back({${atMs},std::move(f)}); }\n`;
  }
  out += "      list.push_back(std::move(fixture)); }\n";
}
out += `    return list;\n  }();\n  return values;\n}\ninline const LabFixture* find_lab_fixture(const std::string& id) {\n  for (const auto& f : lab_fixtures()) if (id == f.id) return &f;\n  return nullptr;\n}\n} // namespace apple::firmware\n`;
const target = "firmware/lib/manager/include/apple/firmware/lab_fixtures.generated.hpp";
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== out)
    throw new Error("Device fixtures are out of date; run pnpm fixtures:generate");
} else await writeFile(target, out);
console.log(
  `${fixtureScenarios.length} shared Simulator fixtures ${process.argv.includes("--check") ? "verified" : "generated"}.`,
);
